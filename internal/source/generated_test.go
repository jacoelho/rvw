// TestGoGeneratedCancelled covers failure propagation: a cancelled read returns the error and
// no partial result.
func TestGoGeneratedCancelled(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	r.write("keep.txt", "base\n")
	r.commit("base")
	r.write("a.go", marker+"package x\n")
	r.commit("head")
	snap := resolve(t, r.dir, source.Last())
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	got, err := snap.GoGenerated(ctx)
	if !errors.Is(err, context.Canceled) || got != nil {
		t.Fatalf("GoGenerated on a cancelled context = %v, %v; want nil and a cancellation error", got, err)
	}
}

// TestGoGeneratedIgnoreCase covers path matching under core.ignoreCase, the macOS default: an
// unchanged file whose path differs from a changed one only in case neither lends nor takes the mark.
func TestGoGeneratedIgnoreCase(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, changed, unchanged string
		changedGenerated         bool
	}{
		{"changed plain, unchanged generated", "gen.go", "Gen.go", false},
		{"changed generated, unchanged plain", "Gen.go", "gen.go", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			r := newRepo(t)
			r.git("config", "core.ignoreCase", "true")
			// The macOS filesystem cannot hold both names, so the trees are built in the index.
			blob := func(content string) string {
				return strings.TrimSpace(string(r.gitInStdin(content, "hash-object", "-w", "--stdin")))
			}
			unchanged := "package x\n"
			if !tc.changedGenerated {
				unchanged = marker + unchanged
			}
			changed := "package x\n"
			if tc.changedGenerated {
				changed = marker + changed
			}
			r.git("update-index", "--add", "--cacheinfo", "100644,"+blob(unchanged)+","+tc.unchanged)
			r.git("update-index", "--add", "--cacheinfo", "100644,"+blob("package x\n\nvar base int\n")+","+tc.changed)
			r.git("commit", "-q", "--no-verify", "-m", "base")
			r.git("update-index", "--cacheinfo", "100644,"+blob(changed)+","+tc.changed)
			r.git("commit", "-q", "--no-verify", "-m", "head")
			snap := resolve(t, r.dir, source.Last())
			if snap.FileCount() != 1 {
				t.Fatalf("%d changed files; the fixture needs only %s", snap.FileCount(), tc.changed)
			}
			want := map[string]bool{}
			if tc.changedGenerated {
				want[tc.changed] = true
			}
			checkGenerated(t, generatedPaths(t, snap), want)
		})
	}
}
