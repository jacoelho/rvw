const marker = "// Code generated by protoc-gen-go. DO NOT EDIT.\n"

// generatedPaths returns the shown paths GoGenerated marks.
func generatedPaths(t *testing.T, snap *source.Snapshot) map[string]bool {
	t.Helper()
	got, err := snap.GoGenerated(t.Context())
	if err != nil {
		t.Fatalf("GoGenerated: %v", err)
	}
	if len(got) != snap.FileCount() {
		t.Fatalf("GoGenerated returned %d entries for %d files", len(got), snap.FileCount())
	}
	out := map[string]bool{}
	for i, g := range got {
		if g {
			f := snap.File(i)
			out[f.Path()] = true
		}
	}
	return out
}

func checkGenerated(t *testing.T, got, want map[string]bool) {
	t.Helper()
	if !maps.Equal(got, want) {
		t.Errorf("generated = %q; want %q", slices.Sorted(maps.Keys(got)), slices.Sorted(maps.Keys(want)))
	}
}

// TestGoGeneratedClassification covers the generated-Go rule on the new side: the marker counts
// only before the package clause, in its exact form, and only in regular .go files.
func TestGoGeneratedClassification(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	r.write("keep.txt", "base\n")
	r.commit("base")
	files := map[string]struct {
		content   string
		generated bool
	}{
		"a.go":            {marker + "\npackage x\n", true},
		"after.go":        {"package x\n\n" + marker, false},
		"buildtag.go":     {"// Copyright 2026.\n\n//go:build linux\n\n" + marker + "\npackage x\n", true},
		"crlf.go":         {strings.ReplaceAll(marker+"\npackage x\n", "\n", "\r\n"), true},
		"block.go":        {"/*\n" + marker + "*/\npackage x\n", true},
		"noeol.go":        {strings.TrimSuffix(marker, "\n"), true},
		"tab.go":          {marker + "package\tx\n", true},
		"tabpkg-first.go": {"package\tx\n" + marker, false},
		"nogen.go":        {"// Code generated DO NOT EDIT.\npackage x\n", false},
		"trailtab.go":     {"// Code generated by x. DO NOT EDIT.\t\npackage x\n", false},
		"trailsp.go":      {"// Code generated by x. DO NOT EDIT. \npackage x\n", false},
		"more.go":         {"// Code generated by x. DO NOT EDIT. Really.\npackage x\n", false},
		"lower.go":        {"// code generated by x. DO NOT EDIT.\npackage x\n", false},
		"nospace.go":      {"//Code generated by x. DO NOT EDIT.\npackage x\n", false},
		"upper.GO":        {marker + "package x\n", false},
		"gen.txt":         {marker, false},
		"gen.go.txt":      {marker, false},
		"plain.go":        {"package x\n", false},
	}
	for p, f := range files {
		r.write(p, f.content)
	}
	r.git("add", "-A")
	// A submodule and a symlink named .go whose content is the marker are not Go source.
	r.git("update-index", "--add", "--cacheinfo", "160000,"+strings.Repeat("ab", 20)+",sub.go")
	id := strings.TrimSpace(string(r.gitInStdin(strings.TrimSuffix(marker, "\n"), "hash-object", "-w", "--stdin")))
	r.git("update-index", "--add", "--cacheinfo", "120000,"+id+",link.go")
	r.git("commit", "-q", "--no-verify", "-m", "head")

	want := map[string]bool{}
	for p, f := range files {
		if f.generated {
			want[p] = true
		}
	}
	checkGenerated(t, generatedPaths(t, resolve(t, r.dir, source.Last())), want)
}

// TestGoGeneratedBinaryBlob covers parse robustness: a blob with a NUL byte neither fails the
// read nor disturbs its siblings' classification.
func TestGoGeneratedBinaryBlob(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	r.write("keep.txt", "base\n")
	r.commit("base")
	r.write("bin.go", "\x00\x01\n"+marker+"package x\n")
	r.write("a.go", marker+"package x\n")
	r.write("b.go", "package x\n")
	r.commit("head")
	got := generatedPaths(t, resolve(t, r.dir, source.Last()))
	delete(got, "bin.go") // unspecified by the contract
	checkGenerated(t, got, map[string]bool{"a.go": true})
}

// TestGoGeneratedShownSide covers the side rule: the new blob, or the old blob when deleted;
// renames are judged on the new path.
func TestGoGeneratedShownSide(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	body := strings.Repeat("var _ = 1\n", 40)
	r.write("deleted.go", marker+"package deleted\n"+strings.Repeat("const d = 1\n", 20))
	r.write("oldonly.go", marker+"package x\n"+body)
	r.write("newonly.go", "package x\n"+body)
	r.write("old.go", marker+"package x\n"+body)
	r.write("gen.go", marker+"package x\n"+body)
	r.commit("base")
	r.remove("deleted.go")
	r.write("oldonly.go", "package x\n"+body)
	r.write("newonly.go", marker+"package x\n"+body)
	r.remove("old.go")
	r.write("new.go", marker+"package x\n"+body)
	r.remove("gen.go")
	r.write("gen.txt", marker+"package x\n"+body)
	r.write("added.go", marker+"package added\n"+strings.Repeat("type a struct{}\n", 20))
	r.commit("head")
	snap := resolve(t, r.dir, source.Last())
	for p, want := range map[string]source.Status{"new.go": source.StatusRenamed, "deleted.go": source.StatusDeleted} {
		if f := snap.File(fileIndex(t, snap, p)); f.Status != want {
			t.Fatalf("%s status %c; the fixture needs %c", p, f.Status, want)
		}
	}
	checkGenerated(t, generatedPaths(t, snap), map[string]bool{
		"deleted.go": true, "newonly.go": true, "new.go": true, "added.go": true,
	})
}

// TestGoGeneratedMissingBlobAndVendored covers files that are not read: a missing blob does not
// fail the batch, and a vendored file is never generated (vendoring takes precedence), while a
// vendor directory with no go.sum beside it is not vendored.
func TestGoGeneratedMissingBlobAndVendored(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	r.write("keep.txt", "base\n")
	r.write("go.sum", "sum\n")
	r.commit("base")
	r.write("a.go", marker+"package a\n")
	r.write("b.go", "package b\n")
	r.write("c.go", marker+"package c\n")
	r.write("vendor/v/gen.go", marker+"package v\n")
	r.write("ng/vendor/g.go", marker+"package g\n")
	r.commit("head")
	r.removeBlob("HEAD", "c.go")
	snap := resolve(t, r.dir, source.Last())
	checkGenerated(t, generatedPaths(t, snap), map[string]bool{"a.go": true, "ng/vendor/g.go": true})
}

// TestGoGeneratedBatches covers pathspec batching and path mapping: more names than one batch
// holds, and names that a glob, magic pathspec or a split at ':' or LF would misread.
func TestGoGeneratedBatches(t *testing.T) {
	t.Parallel()
	r := newRepo(t)
	r.write("keep.txt", "base\n")
	r.commit("base")
	const n = 300
	long := strings.Repeat("n", 240)
	want := map[string]bool{}
	for i := range n {
		p := fmt.Sprintf("%04d-%s.go", i, long)
		if i%3 == 0 || i == n-1 {
			r.write(p, marker+"package x\n")
			want[p] = true
		} else {
			r.write(p, "package x\n")
		}
	}
	for k, p := range []string{"-dash.go", "[br].go", "r.go", "sp ace.go", ":magic.go", "a:b/g.go", "nl\nname.go"} {
		if k%2 == 0 {
			r.write(p, marker+"package x\n")
			want[p] = true
		} else {
			r.write(p, "package x\n")
		}
	}
	r.commit("head")
	checkGenerated(t, generatedPaths(t, resolve(t, r.dir, source.Last())), want)
}

