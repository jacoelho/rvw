const genMarker = "// Code generated by stringer. DO NOT EDIT.\n\n"

// generatedRepo has generated and ordinary Go files: deleted, renamed, vendored, under an
// escaped path, and one that stopped being generated. Each file changes a distinct number of
// lines, so a count on the wrong file shows.
func generatedRepo(t *testing.T) *testRepo {
	t.Helper()
	r := newTestRepo(t)
	r.write("plain.go", "package p\n"+numberedLines("plain", 10))
	r.write("gone_gen.go", genMarker+"package g\n"+numberedLines("gone", 10))
	r.write("old_gen.go", genMarker+"package g\n"+numberedLines("moved", 10))
	r.write("was_gen.go", genMarker+"package w\n"+numberedLines("was", 10))
	r.write("go.sum", "sum\n") // makes vendor/ a vendored directory
	r.commit("base")
	r.write("plain.go", "package p\n"+numberedLines("plain", 10)+"p1\n")
	r.write("gen.go", genMarker+"package g\n"+numberedLines("gen", 2))
	r.remove("gone_gen.go")
	r.git("mv", "old_gen.go", "new_gen.go")
	r.write("new_gen.go", genMarker+"package g\n"+numberedLines("moved", 9)+"moved changed\n")
	r.write("was_gen.go", "package w\n"+numberedLines("was", 10)+"w1\nw2\nw3\n")
	r.write("vendor/lib/gen.go", genMarker+"package lib\n")
	r.write("vendor/lib/plain.go", "package lib\n")
	r.write("a\nb/gen.go", genMarker+"package ab\n")
	r.commit("head")
	return r
}

// generatedStatus is the generated-file part of a /api/status response. A pointer tells an
// absent generated member from an empty one: absent is the contract for "none" and for since > 0.
type generatedStatus struct {
	Generated      *[]int     `json:"generated"`
	GeneratedError string     `json:"generated_error"`
	Counts         []countDTO `json:"counts"`
	Next           int        `json:"next"`
	GeneratedDone  bool       `json:"generated_done"`
	CountsDone     bool       `json:"counts_done"`
}

func (f *fixture) generatedStatus(since int) generatedStatus {
	f.t.Helper()
	r := f.do(http.MethodGet, "/api/status?since="+strconv.Itoa(since), "")
	f.mustStatus(r, http.StatusOK, "GET /api/status")
	var st generatedStatus
	decode(f.t, r.body, &st)
	return st
}

// generatedMarks polls /api/status from 0 until the generated marks are done and returns that
// response. Every response along the way must hold the marks before any count: a count published
// first could belong to a generated file.
func (f *fixture) generatedMarks() generatedStatus {
	f.t.Helper()
	deadline := time.Now().Add(20 * time.Second)
	for {
		st := f.generatedStatus(0)
		if (len(st.Counts) > 0 || st.CountsDone) && !st.GeneratedDone {
			f.t.Fatalf("counts %+v (done %v) reported before the generated marks", st.Counts, st.CountsDone)
		}
		if st.GeneratedDone {
			return st
		}
		if time.Now().After(deadline) {
			f.t.Fatal("generated marks did not finish")
		}
		time.Sleep(20 * time.Millisecond)
	}
}

// TestStatusReportsGeneratedFiles: /api/status lists exactly the generated Go files that are not
// vendored, by file index, including deleted, renamed and escaped paths; a poll past 0 omits them.
func TestStatusReportsGeneratedFiles(t *testing.T) {
	t.Parallel()
	f := newFixture(t, generatedRepo(t), fixtureOptions{})
	f.serveRun()
	s := f.session()
	if i := s.fileIndex(t, "new_gen.go"); s.Files[i].Status != "R" {
		t.Fatalf("new_gen.go: status %s; the fixture needs a rename", s.Files[i].Status)
	}
	var want []int
	for _, p := range []string{"gen.go", "gone_gen.go", "new_gen.go", `a\nb/gen.go`} {
		want = append(want, s.fileIndex(t, p))
	}
	slices.Sort(want)
	st := f.generatedMarks()
	if st.GeneratedError != "" {
		t.Fatalf("generated_error %q", st.GeneratedError)
	}
	if st.Generated == nil || !slices.Equal(*st.Generated, want) {
		t.Errorf("generated %v; want %v (gen.go, gone_gen.go, new_gen.go, a\\nb/gen.go)", st.Generated, want)
	}
	f.lineCounts() // the cursor moves past 0 only once a count exists
	if later := f.generatedStatus(1); later.Generated != nil || later.GeneratedDone {
		t.Errorf("since=1: generated %v, generated_done %v; want both absent", later.Generated, later.GeneratedDone)
	}
}

// TestStatusOmitsGeneratedWhenNone: with no generated file the marks finish with no generated member.
func TestStatusOmitsGeneratedWhenNone(t *testing.T) {
	t.Parallel()
	r := newTestRepo(t)
	r.write("a.go", "package a\n")
	r.commit("base")
	r.write("a.go", "package a\n\nvar x int\n")
	r.commit("head")
	f := newFixture(t, r, fixtureOptions{})
	f.serveRun()
	if st := f.generatedMarks(); st.Generated != nil || st.GeneratedError != "" {
		t.Errorf("generated %v, generated_error %q; want both absent", st.Generated, st.GeneratedError)
	}
}

// TestGeneratedFailureKeepsCounts: when git cannot read the generated marks, the status reports
// the error, marks nothing, and every non-vendored file, the generated ones included, is counted.
func TestGeneratedFailureKeepsCounts(t *testing.T) {
	t.Parallel()
	r := generatedRepo(t)
	r.git("config", "grep.threads", "notanumber") // git grep dies on it; diff never reads it
	f := newFixture(t, r, fixtureOptions{})
	f.serveRun()
	st := f.generatedMarks()
	if st.GeneratedError == "" || st.Generated != nil {
		t.Errorf("generated %v, generated_error %q; want no marks and an error", st.Generated, st.GeneratedError)
	}
	s := f.session()
	got := f.lineCounts()
	for _, p := range []string{"plain.go", "was_gen.go", "gen.go", "gone_gen.go", "new_gen.go", `a\nb/gen.go`} {
		if _, ok := got[s.fileIndex(t, p)]; !ok {
			t.Errorf("%s: no line count", p)
		}
	}
	for _, p := range []string{"vendor/lib/gen.go", "vendor/lib/plain.go"} {
		if _, ok := got[s.fileIndex(t, p)]; ok {
			t.Errorf("%s: vendored file counted", p)
		}
	}
}

// TestCountsSkipGeneratedFiles: generated and vendored files get no line count; the others keep
// theirs, under their own index, including a file that stopped being generated.
func TestCountsSkipGeneratedFiles(t *testing.T) {
	t.Parallel()
	f := newFixture(t, generatedRepo(t), fixtureOptions{})
	f.serveRun()
	s := f.session()
	want := map[int]countDTO{}
	for path, c := range map[string]countDTO{
		"plain.go":   {Added: 1},
		"was_gen.go": {Added: 3, Deleted: 2},
	} {
		i := s.fileIndex(t, path)
		c.I = i
		want[i] = c
	}
	if got := f.lineCounts(); !maps.Equal(got, want) {
		t.Errorf("counts %+v; want %+v (indexes of plain.go, was_gen.go)", got, want)
	}
}
