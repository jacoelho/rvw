// Regenerates web/src/icons/ from a checkout of https://github.com/catppuccin/vscode-icons:
//
//   node web/scripts/icons.mjs <checkout>
//
// It keeps the curated icons below, rewrites their colours from VS Code's --vscode-ctp-* variables
// to app.css's --ctp-* ones, and writes one sprite plus the file-name and extension tables those
// icons claim upstream. The UI bundles a subset because every icon ships in the page; an icon
// added here needs nothing else.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, resolve } from "node:path";

const ICONS = [
  "_file", "_folder", "_folder_open",
  // Languages.
  "go", "go-mod", "go-template",
  "typescript", "typescript-react", "typescript-test", "typescript-def", "typescript-config",
  "javascript", "javascript-react", "javascript-test", "javascript-config", "javascript-map",
  "bash", "powershell", "batch", "python", "python-config", "rust", "rust-config", "cargo", "cargo-lock",
  "java", "kotlin", "scala", "groovy", "swift", "c", "c-header", "cpp", "cpp-header", "csharp", "fsharp",
  "ruby", "php", "lua", "perl", "r", "elixir", "erlang", "haskell", "ocaml", "clojure", "dart", "zig",
  "nim", "julia", "assembly", "solidity", "proto", "graphql", "database",
  // Web.
  "html", "css", "sass", "less", "postcss", "tailwind", "vue", "svelte", "astro",
  // Data and configuration.
  "json", "json-schema", "yaml", "toml", "xml", "properties", "env", "config", "editorconfig", "csv",
  "markdown", "markdown-mdx", "latex", "text", "log", "diff",
  // Repository files.
  "readme", "changelog", "license", "contributing", "code-of-conduct", "codeowners", "todo",
  "git", "workflow", "dependabot", "renovate", "pre-commit",
  // Build and tooling.
  "makefile", "cmake", "just", "taskfile", "bazel", "gradle", "docker", "docker-compose", "docker-ignore",
  "nix", "nix-lock", "terraform", "helm", "nginx",
  "npm", "npm-ignore", "npm-lock", "package-json", "pnpm", "pnpm-lock", "yarn", "yarn-lock", "bun", "bun-lock",
  "lock", "eslint", "eslint-ignore", "prettier", "prettier-ignore", "biome", "vite", "vitest", "jest",
  "esbuild", "webpack", "rollup", "playwright",
  // Binary and media.
  "image", "svg", "font", "audio", "video", "pdf", "zip", "binary", "exe", "web-assembly",
  "certificate", "key", "security",
];

const checkout = process.argv[2];
if (!checkout) {
  console.error("usage: node web/scripts/icons.mjs <catppuccin/vscode-icons checkout>");
  process.exit(2);
}
const commit = execFileSync("git", ["-C", checkout, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const out = resolve(import.meta.dirname, "../src/icons");

// The associations are one object literal of string arrays; reading it as JSON, not running it,
// fails loudly if upstream ever puts code in it.
const source = readFileSync(join(checkout, "src/defaults/fileIcons.ts"), "utf8");
const start = source.indexOf("{", source.indexOf("const fileIcons"));
const end = source.indexOf("\n}\n", start);
if (start < 0 || end < 0) throw new Error("fileIcons.ts: object literal not found");
const json = source
  .slice(start, end + 2)
  .replace(/\/\/.*$/gm, "")
  .replace(/'/g, '"')
  .replace(/^(\s*)([A-Za-z]\w*):/gm, '$1"$2":')
  .replace(/,(\s*[\]}])/g, "$1");
const associations = JSON.parse(json);

const names = new Map();
const exts = new Map();
const symbols = [];
for (const icon of ICONS) {
  const svg = readFileSync(join(checkout, "icons/css-variables", `${icon}.svg`), "utf8");
  if (!/viewBox="0 0 16 16"/.test(svg)) throw new Error(`${icon}.svg: viewBox is not 0 0 16 16`);
  const inner = svg
    .slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"))
    .replace(/var\(--vscode-ctp-([a-z0-9]+)\)/g, "var(--ctp-$1)")
    .replace(/\s*\n\s*/g, "");
  if (/--vscode-|<script|\son\w+=/i.test(inner)) throw new Error(`${icon}.svg: unexpected content`);
  symbols.push(`<symbol id="i-${icon}" viewBox="0 0 16 16">${inner}</symbol>`);
}
// Upstream order decides a key two icons claim: the later one wins, as in the extension itself.
const kept = new Set(ICONS);
for (const [icon, a] of Object.entries(associations)) {
  if (!kept.has(icon)) continue;
  for (const n of a.fileNames ?? []) names.set(n.toLowerCase(), icon);
  for (const e of a.fileExtensions ?? []) exts.set(e.toLowerCase(), icon);
}

const origin = `catppuccin/vscode-icons ${commit}, MIT licence (LICENSE in this directory)`;
writeFileSync(
  join(out, "sprite.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" width="0" height="0" class="icon-sprite"><!-- ${origin}; generated by web/scripts/icons.mjs -->${symbols.join("")}</svg>\n`,
);
// Maps, not object literals: a lookup of a name such as "constructor" or "__proto__" must not
// find an Object.prototype member.
const table = (m) =>
  "new Map([\n" + [...m.keys()].sort().map((k) => `  [${JSON.stringify(k)}, ${JSON.stringify(m.get(k))}],`).join("\n") + "\n])";
writeFileSync(
  join(out, "associations.ts"),
  `// Generated by web/scripts/icons.mjs from ${origin}. Do not edit.\n\n` +
    `/** Icon by lower-case file name. */\nexport const FILE_NAMES: ReadonlyMap<string, string> = ${table(names)};\n\n` +
    `/** Icon by lower-case extension, without the leading dot; an extension may hold dots. */\nexport const EXTENSIONS: ReadonlyMap<string, string> = ${table(exts)};\n`,
);
writeFileSync(join(out, "LICENSE"), readFileSync(join(checkout, "LICENSE")));
console.log(`${ICONS.length} icons, ${names.size} file names, ${exts.size} extensions`);
